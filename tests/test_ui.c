#define _GNU_SOURCE
#include "../src/system/ui/ui.c"
#include <assert.h>
#include <stdio.h>
static void touch(int kind, int x, int y) {
    Input in = {.kind = kind, .x = x, .y = y};
    ui_input(&in);
    ui_draw();
}
int main(int argc, char **argv) {
    assert(argc == 3);
    library_root = argv[1];
    data_root = argv[2];
    assert(engine_init());
    library_scan();
    ui_init();
    assert(screen == 1 && settings.grid == 1 && settings.filter == 0);
    assert(settings.size == 24 && options[OPT_COVER_CROP] && options[OPT_COVER_RADIUS] &&
           options[OPT_APPS] && !options[OPT_TAB_LABELS] && !options[OPT_BATTERY_PERCENT]);
    options[OPT_APPS] = 0;
    memset(ui_pixels, 255, sizeof(ui_pixels));
    button_h(100, 100, 300, 48, "Äpfel & Bücher", 0);
    int top = 800, bottom = -1;
    for (int y = 100; y < 148; y++)
        for (int x = 100; x < 400; x++)
            if (ui_pixels[y * 600 + x] < 160) {
                if (y < top)
                    top = y;
                if (y > bottom)
                    bottom = y;
            }
    assert(abs(top + bottom - 247) <= 1);
    ui_draw();
    touch(INPUT_TAP, 220, 85);
    assert(screen == 1 && !keyboard && !dropdown);
    assert(ui_pixels[750 * 600 + 210] == 255);
    touch(INPUT_DOWN, 300, 770);
    assert(ui_pixels[750 * 600 + 210] == 0);
    touch(INPUT_TAP, 300, 770);
    assert(screen == 13);
    touch(INPUT_TAP, 300, 161);
    assert(screen == 12 && wifi_count == 2);
    touch(INPUT_TAP, 28, 22);
    assert(screen == 13);
    touch(INPUT_TAP, 300, 238);
    assert(screen == 8);
    touch(INPUT_TAP, 28, 22);
    assert(screen == 13);
    touch(INPUT_TAP, 500, 770);
    assert(screen == 10 && opds_count >= 20);
    touch(INPUT_TAP, 250, 245);
    assert(screen == 11 && opds_items[opds_selected].acquisition);
    touch(INPUT_TAP, 100, 770);
    assert(screen == 1);
    touch(INPUT_DOWN, 300, 770);
    touch(INPUT_MOVE, 300, 350);
    touch(INPUT_TAP, 300, 350);
    assert(screen == 1);
    int v[BOOK_LIMIT];
    assert(library_view(v, "apfel", 0, 0) == 1);
    assert(ui_open(v[0]));
    assert(!reader_chrome);
    ui_draw();
    assert(widget_count == 0);
    int old = page;
    touch(INPUT_TAP, 300, 20);
    assert(reader_chrome && page == old);
    touch(INPUT_TAP, 300, 780);
    assert(!reader_chrome);
    touch(INPUT_TAP, 500, 350);
    assert(page == old + 1);
    Input sleep = {.kind = INPUT_SLEEP}, wake = {.kind = INPUT_WAKE},
          down = {.kind = INPUT_POWER, .x = 1}, up = {.kind = INPUT_POWER, .x = 0};
    ui_input(&down);
    ui_input(&sleep);
    ui_input(&up);
    assert(sleeping);
    ui_input(&wake);
    assert(!sleeping);
    ui_input(&sleep);
    ui_input(&down);
    ui_input(&up);
    assert(!sleeping);
    ui_draw();
    touch(INPUT_TAP, 300, 20);
    touch(INPUT_TAP, 226, 718);
    assert(screen == 3);
    touch(INPUT_TAP, 100, 770);
    assert(screen == 1);
    memset(ui_pixels, 255, sizeof(ui_pixels));
    Book placeholder = {0};
    snprintf(placeholder.title, sizeof(placeholder.title), "Square cover");
    options[OPT_COVER_RADIUS] = 0;
    cover_size(&placeholder, 30, 30, 120, 164);
    assert(ui_pixels[30 * 600 + 30] < 255);
    options[OPT_LANGUAGE] = 1;
    assert(!strcmp(tr("Einstellungen"), "Settings"));
    assert(!strcmp(tr("Bücher übertragen"), "Transfer books"));
    screen = 9;
    setting_category = 1;
    ui_draw();
    assert(widget_count >= 11);
    options[OPT_LANGUAGE] = 0;
    network_results();
    assert(network_forget(0));
    assert(!wifi_networks[0].saved && wifi_networks[0].network_id == -1);
    char config[2048];
    snprintf(config, sizeof(config), "%s/config.txt", data_root);
    assert(library_config_export(config));
    int oldclock = options[OPT_CLOCK];
    options[OPT_CLOCK] = !oldclock;
    assert(library_config_import(config));
    assert(options[OPT_CLOCK] == oldclock);
    assert(!strcmp(author_label("Schätzing, Frank", config, sizeof(config)), "Frank Schätzing"));
    screen = 1;
    keyboard = dropdown = confirm_delete = battery_popup = 0;
    assert(!can_back());
    screen = 13;
    assert(!can_back());
    screen = 12;
    assert(can_back());
    screen = 1;
    options[OPT_BATTERY_PERCENT] = 0;
    ui_draw();
    touch(INPUT_TAP, 550, 22);
    assert(battery_popup);
    touch(INPUT_TAP, 100, 200);
    assert(!battery_popup);
    screen = 9;
    setting_category = 1;
    setting_page = 0;
    ui_draw();
    touch(INPUT_TAP, 370, 700);
    assert(setting_page == 1);
    touch(INPUT_TAP, 225, 700);
    assert(setting_page == 0);
    options[OPT_LANGUAGE] = 0;
    assert(ui_open(v[0]));
    page = 1;
    reader_chrome = 0;
    notice[0] = 0;
    ui_draw();
    TextSelection found;
    assert(engine_find_text(page, "Lesen", 544, 728, zoom, panx, pany, &found));
    TextRect r = found.rects[0];
    int xx = (int)((r.x0 + r.x1) / 2) + 28, yy = (int)((r.y0 + r.y1) / 2) + 12;
    if (yy < 61)
        yy = 61;
    touch(INPUT_HOLD, xx, yy);
    assert(selecting == 1);
    touch(INPUT_TAP, xx + 1, yy + 1);
    assert(selecting == 2);
    int oldnotes = annotation_count;
    touch(INPUT_TAP, 100, 690);
    assert(selecting == 0 && annotation_count == oldnotes + 1);
    annotations_load();
    assert(annotation_count == oldnotes + 1);
    screen = 14;
    notice[0] = 0;
    ui_draw();
    touch(INPUT_TAP, 545, 190);
    assert(confirm_delete == 2);
    touch(INPUT_TAP, 430, 470);
    assert(annotation_count == oldnotes && !confirm_delete);
    options[OPT_LANGUAGE] = 1;
    memset(ui_pixels, 255, sizeof(ui_pixels));
    drawtext_raw(10, 10, "Offenes Netz", &small, 300);
    unsigned char literal[600 * 50];
    memcpy(literal, ui_pixels, sizeof(literal));
    memset(ui_pixels, 255, sizeof(ui_pixels));
    drawtext(10, 10, "Offenes Netz", &small, 300);
    assert(memcmp(literal, ui_pixels, sizeof(literal)) != 0);

    screen = 1;
    reader_chrome = 0;
    keyboard = dropdown = battery_popup = 0;
    history_count = 0;
    options[OPT_COVER_RADIUS] = 1;
    memset(ui_pixels, 255, sizeof(ui_pixels));
    cover_size(&placeholder, 30, 30, 120, 164);
    assert(ui_pixels[30 * 600 + 30] == 255 && ui_pixels[100 * 600 + 80] < 255);
    int aa = 0;
    for (int y = 30; y < 39; y++)
        for (int x = 30; x < 39; x++)
            if (ui_pixels[y * 600 + x] > 238 && ui_pixels[y * 600 + x] < 255)
                aa++;
    assert(aa > 0);
    options[OPT_APPS] = 1;
    ui_draw();
    touch(INPUT_TAP, 525, 770);
    assert(screen == 20 && !can_back());
    touch(INPUT_TAP, 100, 200);
    assert(screen == 27);
    touch(INPUT_TAP, 28, 22);
    assert(screen == 20);
    app_open(21);
    ui_draw();
    assert(screen == 21 && can_back());
    calendar_year = 2028;
    calendar_month = 2;
    calendar_day = 29;
    apps_note_commit("Leap day / Schöne Bücher");
    calendar_note[0] = 0;
    app_calendar_load();
    assert(strstr(calendar_note, "Schöne"));
    touch(INPUT_TAP, 28, 22);
    assert(screen == 20);
    app_open(23);
    ui_draw();
    assert(screen == 23);
    touch(INPUT_HOLD, 90, 190);
    assert(mine_game.flag[0]);
    touch(INPUT_TAP, 90, 190);
    assert(mine_game.flag[0] && !mine_game.started);
    touch(INPUT_TAP, 28, 22);
    app_open(25);
    ui_draw();
    assert(screen == 25 && block_game.paused && apps_poll_interval() == -1);
    touch(INPUT_TAP, 480, 140);
    assert(!block_game.paused && ui_poll_interval() >= 0);
    touch(INPUT_TAP, 28, 22);
    assert(screen == 20 && block_game.paused && apps_poll_interval() == -1);
    app_open(26);
    ui_draw();
    assert(screen == 26);
    touch(INPUT_TAP, 480, 140);
    assert(!snake_game.paused);
    ui_input(&sleep);
    assert(sleeping && snake_game.paused && ui_poll_interval() == -1);
    ui_input(&wake);
    screen = 2;
    sleeping = 0;
    unsigned seconds = app_data.seconds;
    app_last_time = app_millis() - 2100;
    apps_checkpoint();
    assert(app_data.seconds == seconds + 2);
    sleeping = 1;
    app_last_time = app_millis() - 100000;
    apps_checkpoint();
    assert(app_data.seconds == seconds + 2);
    sleeping = 0;
    options[OPT_APPS] = 0;
    app_last_time = app_millis() - 10000;
    apps_checkpoint();
    assert(app_data.seconds == seconds + 2);
    options[OPT_APPS] = 1;
    screen = 3;
    reading_page = 0;
    int size = settings.size;
    touch(INPUT_TAP, 545, 260);
    assert(settings.size == size + 2);
    touch(INPUT_TAP, 370, 700);
    assert(reading_page == 1);
    int progress = options[OPT_PROGRESS];
    touch(INPUT_TAP, 530, 420);
    assert(options[OPT_PROGRESS] != progress);
    int epoch = layout_epoch;
    apply_reading_settings();
    assert(layout_epoch == epoch + 1);
    epoch = layout_epoch;
    apply_reading_settings();
    assert(layout_epoch == epoch);
    ui_save();
    unsigned pages = app_data.pages;
    apps_init();
    assert(app_data.seconds == seconds + 2 && app_data.pages == pages);
    /* Older configurations receive defaults once; later personal choices survive reload. */
    char opath[2048], spath[2048];
    snprintf(opath, sizeof(opath), "%s/options-v3.txt", data_root);
    snprintf(spath, sizeof(spath), "%s/settings.txt", data_root);
    assert(atomic_write(opath, "22 1\n23 0\n24 0\n", 15));
    const char *oldsettings = "LUMEN2 28 145 12 8 1 0 0\n";
    assert(atomic_write(spath, oldsettings, strlen(oldsettings)));
    library_settings_load();
    assert(settings.size == 28 && !options[OPT_BATTERY_PERCENT] && options[OPT_COVER_RADIUS] &&
           options[OPT_COVER_CROP]);
    settings.size = 22;
    options[OPT_COVER_RADIUS] = 0;
    options[OPT_BATTERY_PERCENT] = 1;
    library_settings_save();
    library_settings_load();
    assert(settings.size == 22 && !options[OPT_COVER_RADIUS] && options[OPT_BATTERY_PERCENT]);
    engine_shutdown();
    puts("PASS: clean Home, three/four tabs, apps, calendar notes, stats, pause/sleep, migration, "
         "settings hierarchy, real cached catalogue, "
         "press/cancel, optical centering, immersive reader, square covers and power "
         "press/release wake state machine.");
}
